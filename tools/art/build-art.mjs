/** Assemble production art from the saved generated source atlases. Never overwrites V0.2 originals. */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { readPng, savePng, canvas, cell, crop, resize, blit, fit, rect } from './png.mjs';
const OUT = 'public/assets/art';
mkdirSync(OUT, { recursive: true });
const heroes = { vishdal: 'demolitionist', amiya: 'sorcerer', saria: 'knight', muelsyse: 'tactician' };
for (const [id, name] of Object.entries(heroes)) {
    const source = readPng(`art/source/${name}-source.png`), sheet = canvas(864, 480);
    for (let row = 0; row < 4; row++) {
        const sr = row === 3 ? 1 : row;
        const poses = [0, 0, 1, 0, 1, 0, 2, 2, 3];
        for (let col = 0; col < 9; col++) {
            const frame = fit(cell(source, poses[col], sr, 4, 4), 96, 96, 92);
            // Two-pose cadence; only whole-figure movement, source foot alignment stays stable.
            blit(sheet, frame, col * 96, row * 96, row === 3);
        }
    }
    for (let i = 0; i < 8; i++) {
        const row = i === 0 ? 2 : i <= 2 ? 1 : i <= 4 ? 0 : i <= 6 ? 3 : 2;
        const frame = cell(sheet, 6, row, 9, 5);
        blit(sheet, frame, i * 96, 384);
    }
    savePng(`${OUT}/hero-${id}.png`, sheet);
    savePng(`${OUT}/portrait-${id}.png`, fit(cell(source, 0, 0, 4, 4), 256, 256, 250));
}
const monsterIds = ['blob', 'skitter', 'spitter', 'charger', 'bulwark', 'mender', 'bomber', 'broodmother', 'boss'];
const monsters = readPng('art/source/monsters-source.png');
for (let i = 0; i < monsterIds.length; i++)
    savePng(`${OUT}/enemy-${monsterIds[i]}.png`, fit(cell(monsters, i % 3, Math.floor(i / 3), 3, 3), monsterIds[i] === 'boss' ? 192 : 80, monsterIds[i] === 'boss' ? 192 : 80));
const brood = cell(monsters, 1, 2, 3, 3);
savePng(`${OUT}/enemy-larva.png`, fit(crop(brood, Math.floor(brood.w * .06), Math.floor(brood.h * .62), Math.floor(brood.w * .45), Math.floor(brood.h * .35)), 48, 48));
const floor = readPng('art/source/arena-source.png');
savePng(`${OUT}/arena.png`, resize(resize(floor, 720, 480, { quant: 16, brightness: .76 }), 1440, 960, { quant: 1 }));
savePng(`${OUT}/title.png`, resize(readPng('art/source/title-source.png'), 1200, 800, { quant: 12, alpha: false }));
// Editable, seamless masonry textures. Relief, gold seams and moss are decorative, not colliders.
for (const type of ['wall', 'cover']) {
    const a = canvas(64, 32);
    rect(a, 0, 0, 64, 32, [13, 24, 31]);
    for (let r = 0; r < 2; r++)
        for (let c = 0; c < 4; c++) {
            let x = c * 16 + (r % 2 ? 8 : 0);
            rect(a, x, 2 + r * 14, 15, 12, [31 + r * 5, 49 + r * 5, 58 + r * 5]);
            rect(a, x, 2 + r * 14, 15, 2, [67, 83, 87]);
            rect(a, x, 12 + r * 14, 15, 2, [10, 19, 25]);
        }
    rect(a, 0, 0, 64, 2, [121, 107, 69]);
    rect(a, 0, 30, 64, 2, [5, 14, 20]);
    if (type === 'cover') {
        rect(a, 23, 6, 18, 18, [17, 36, 43]);
        rect(a, 28, 8, 8, 14, [135, 116, 62]);
        rect(a, 30, 10, 4, 10, [87, 214, 202]);
    }
    savePng(`${OUT}/${type}.png`, resize(a, 32, 32, { quant: 1 }));
}
const groups = [['loot', 6, 6, [...Array.from({ length: 24 }, (_, i) => `I${String(i + 1).padStart(2, '0')}`), ...Array.from({ length: 8 }, (_, i) => `P${String(i + 1).padStart(2, '0')}`), 'coin', 'key', 'chest', 'xp']], ['powers', 4, 4, [...Array.from({ length: 12 }, (_, i) => `S${String(i + 1).padStart(2, '0')}`), 'attack', 'spell', 'dash', 'grenade']], ['relics', 4, 4, [...Array.from({ length: 8 }, (_, i) => `E${String(i + 1).padStart(2, '0')}`), ...Array.from({ length: 6 }, (_, i) => `R${String(i + 1).padStart(2, '0')}`), 'hex-gold', 'hex-silver']]];
const icons = {};
for (const [name, cols, rows, ids] of groups) {
    const source = readPng(`art/source/${name}-source.png`);
    ids.forEach((id, i) => { const img = fit(cell(source, i % cols, Math.floor(i / cols), cols, rows), 64, 64, 60); savePng(`${OUT}/icon-${id}.png`, img); icons[id] = `/assets/art/icon-${id}.png`; });
}
const catalog = JSON.parse(readFileSync('docs/design/v0.2/data/catalog.json', 'utf8'));
// Hexes share the relevant illustrated mechanism, plus their own UI rarity/frame and label.
const hexIcons = ['spell', 'grenade', 'I03', 'I02', 'I06', 'dash', 'S09', 'I08', 'I06', 'coin', 'I10', 'coin', 'I03', 'I14', 'I02', 'spell', 'S07', 'I01', 'I19', 'I12', 'S11', 'E08', 'P01', 'I23', 'grenade', 'I24', 'I02', 'E04', 'I13', 'grenade', 'spell', 'E02', 'S03', 'E01', 'S08', 'spell', 'S06', 'S07', 'S07', 'I06', 'S07', 'E03', 'S09', 'P07', 'S08', 'E04', 'S09', 'E04'];
for (let i = 0; i < 48; i++)
    icons[`H${String(i + 1).padStart(2, '0')}`] = icons[hexIcons[i]];
const names = {};
for (const group of Object.values(catalog))
    if (Array.isArray(group))
        for (const x of group)
            if (x.id && x.name)
                names[x.name] = icons[x.id];
writeFileSync('src/game/art-manifest.ts', `/** Generated by tools/art/build-art.mjs. Full literal paths are required for offline inlining. */\nexport const ENEMY_ART = ${JSON.stringify(Object.fromEntries([...monsterIds, 'larva'].map(id => [id, `/assets/art/enemy-${id}.png`])), null, 2)} as const;\nexport const ITEM_ART: Readonly<Record<string,string>> = ${JSON.stringify(icons, null, 2)};\nexport const NAME_ART: Readonly<Record<string,string>> = ${JSON.stringify(names, null, 2)};\nexport const EXTRA_ART = { chest: '/assets/art/icon-chest.png', coin: '/assets/art/icon-coin.png', dash: '/assets/art/icon-dash.png', grenade: '/assets/art/icon-grenade.png' } as const;\n`);
console.log('Art built: four directional hero sheets + portraits, 10 enemy textures, arena, masonry and illustrated UI atlas.');
// Four frame flame/ice/tide/arcane bursts preserve their phase size and transparent margins.
const fxSource = readPng('art/source/fx-source.png'), fxSheet = canvas(512, 512);
for (let r = 0; r < 4; r++)
    for (let c = 0; c < 4; c++)
        blit(fxSheet, resize(cell(fxSource, c, r, 4, 4), 120, 120), c * 128 + 4, r * 128 + 4);
savePng(`${OUT}/effects.png`, fxSheet);
writeFileSync('src/game/art-manifest.ts', readFileSync('src/game/art-manifest.ts', 'utf8') + "export const FX_ART = '/assets/art/effects.png';\n");

